# Fetches a CC0 sky HDRI from Poly Haven into assets/hdri/.
#
# Poly Haven publishes every HDRI under CC0 1.0 (public domain), so the file can
# ship with the game. The game loads it as a panorama sky and rotates it so the
# HDRI's own sun lines up with the DirectionalLight3D; without the file it falls
# back to the procedural sky.
#
# Usage (from the project root):
#   powershell -ExecutionPolicy Bypass -File tools/fetch_cc0_hdri.ps1
#   powershell -ExecutionPolicy Bypass -File tools/fetch_cc0_hdri.ps1 -Id kloppenheim_06_puresky

param(
    [string]$Id = "kloofendal_43d_clear_puresky",
    [string]$Dest = (Join-Path (Split-Path $PSScriptRoot -Parent) "assets\hdri")
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

New-Item -ItemType Directory -Force -Path $Dest | Out-Null

Write-Host ("fetch HDRI " + $Id)
$files = Invoke-RestMethod -Uri ("https://api.polyhaven.com/files/" + $Id) -TimeoutSec 60
$hdr = $files.hdri.'1k'.hdr
if (-not $hdr) { throw ($Id + " has no 1k .hdr") }

$dst = Join-Path $Dest "sky.hdr"
$need = $true
if (Test-Path $dst) {
    $have = (Get-FileHash -Path $dst -Algorithm MD5).Hash.ToLower()
    if ($have -eq $hdr.md5.ToLower()) { $need = $false }
}
if ($need) {
    Invoke-WebRequest -Uri $hdr.url -OutFile $dst -TimeoutSec 300
    $have = (Get-FileHash -Path $dst -Algorithm MD5).Hash.ToLower()
    if ($have -ne $hdr.md5.ToLower()) { throw "md5 mismatch for sky.hdr" }
}
Write-Host ("  sky.hdr " + [math]::Round((Get-Item $dst).Length / 1KB) + " KB")

# Locate the baked sun so the game can aim its directional light at it.
$sun = Join-Path $Dest "sun.json"
$py = Get-Command python -ErrorAction SilentlyContinue
if ($py) {
    & python (Join-Path $PSScriptRoot "hdri_sun.py") $dst $sun $Id
} else {
    Write-Warning "python not found: skipping sun.json (the sky will not be rotated)"
}

$license = @"
CC0 1.0 Universal (public domain) sky HDRI.

Source: Poly Haven - https://polyhaven.com/a/$Id
File  : sky.hdr (1k Radiance .hdr, unmodified)

Poly Haven releases its HDRIs under CC0 1.0, so attribution is not required;
this notice is kept for provenance.

sun.json is generated by tools/hdri_sun.py: it records the azimuth/elevation of
the brightest pixel so EnvBuilder can rotate the panorama and point the
DirectionalLight3D at the same sun.

Delete this folder (or rename sky.hdr) to fall back to the procedural sky.
"@
Set-Content -Path (Join-Path $Dest "LICENSE.txt") -Value $license -Encoding UTF8

Write-Host ("hdri -> " + $Dest)
